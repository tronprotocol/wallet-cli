// Builds plugin-sdk/dist: type declarations of the five plugin-api entries, one runtime module per
// entry that binds each export to the API object the host publishes, and the self-contained `testing`
// entry that publishes the real API for plugin tests. Run with `node --import tsx`; an optional
// argument names another output directory, for tests that must not touch plugin-sdk/dist.
import process from "node:process";
import { mkdirSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { build } from "tsup";
import { PLUGIN_API_GLOBAL, PLUGIN_API_OBJECT } from "../src/bootstrap/plugins/api-object.ts";
import { PLUGIN_API_REVISION, PLUGIN_API_VERSION } from "../src/plugin-api/index.ts";

const OUT = process.argv[2] ?? "plugin-sdk/dist";
const ENTRIES = ["index", "domain", "application", "cli", "http"];
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

rmSync(OUT, { recursive: true, force: true });
// The testing runtime inlines everything, so the API object, its Zod and the test seams are one copy.
// Built in its own directory: tsup builds of one directory remove each other's output.
const TESTING_OUT = process.argv[2] ? `${OUT}.testing` : "plugin-sdk/.testing";
rmSync(TESTING_OUT, { recursive: true, force: true });
await build({
  entry: { testing: "plugin-sdk/src/testing.ts" },
  outDir: TESTING_OUT,
  format: ["esm"],
  platform: "node",
  target: "node22",
  outExtension: () => ({ js: ".mjs" }),
  noExternal: [/.*/],
  // Inlined CommonJS packages call require for Node's own modules, which an ES module does not have.
  banner: {
    js: 'import { createRequire as sdkCreateRequire } from "node:module";\nconst require = sdkCreateRequire(import.meta.url);',
  },
  tsconfig: "tsconfig.json",
  silent: true,
});
// One declaration build, so testing.d.ts shares the declarations of the other entries.
await build({
  entry: {
    ...Object.fromEntries(ENTRIES.map((e) => [e, `src/plugin-api/${e}.ts`])),
    testing: "plugin-sdk/src/testing.ts",
  },
  outDir: OUT,
  format: ["esm"],
  // tsup sets baseUrl for the declaration build, which TypeScript 6 reports as deprecated.
  dts: { only: true, compilerOptions: { ignoreDeprecations: "6.0" } },
  external: ["zod"],
  tsconfig: "tsconfig.json",
  silent: true,
});

const key = PLUGIN_API_GLOBAL.description;
for (const entry of ENTRIES) {
  const names = Object.keys(PLUGIN_API_OBJECT[entry]).sort();
  for (const name of names) {
    if (!IDENTIFIER.test(name) || name === "default") throw new Error(`cannot export ${name}`);
  }
  const lines = [`// Generated by scripts/build-plugin-sdk.mjs.`];
  if (entry === "index") {
    // The numbers this SDK was built for; a plugin declares them, so they never come from the host.
    lines.push(
      `export const PLUGIN_API_VERSION = ${PLUGIN_API_VERSION};`,
      `export const PLUGIN_API_REVISION = ${PLUGIN_API_REVISION};`,
    );
    const others = names.filter((n) => n !== "PLUGIN_API_VERSION" && n !== "PLUGIN_API_REVISION");
    if (others.length > 0)
      throw new Error(`index has runtime exports to bind: ${others.join(", ")}`);
  } else {
    lines.push(
      `const host = globalThis[Symbol.for(${JSON.stringify(key)})];`,
      `if (host === undefined) {`,
      `  throw new Error("@tron-walletcli/plugin-sdk/${entry} works only inside wallet-cli: no wallet-cli plugin API is present in this process");`,
      `}`,
      `const api = host.${entry};`,
      ...names.map((name) => `export const ${name} = api.${name};`),
    );
  }
  writeFileSync(`${OUT}/${entry}.mjs`, `${lines.join("\n")}\n`);
}
mkdirSync(OUT, { recursive: true });
for (const file of readdirSync(TESTING_OUT)) renameSync(`${TESTING_OUT}/${file}`, `${OUT}/${file}`);
rmSync(TESTING_OUT, { recursive: true, force: true });
writeFileSync(
  `${OUT}/version.json`,
  `${JSON.stringify({ apiVersion: PLUGIN_API_VERSION, apiRevision: PLUGIN_API_REVISION })}\n`,
);
console.log(`plugin-sdk built for plugin API ${PLUGIN_API_VERSION}.${PLUGIN_API_REVISION}`);
